package nl.clockwork.ebms.api;

import jakarta.ws.rs.WebApplicationException;
import jakarta.ws.rs.core.Response;
import jakarta.ws.rs.ext.ExceptionMapper;
import jakarta.ws.rs.ext.Provider;
import lombok.extern.slf4j.Slf4j;

@Slf4j
@Provider
public class EbMSExceptionMapper implements ExceptionMapper<Exception>
{
	@Override
	public Response toResponse(Exception ex)
	{
		log.error("Exception in REST endpoint", ex);
		WithController withController = new WithController()
		{
		};
		WebApplicationException webEx = withController.toWebApplicationException(ex);
		return webEx.getResponse();
	}
}
